type TopicAngle = { title: string; approach: string; reason: string };

function comparisonKey(text: string) {
  return text.replace(/[\s\p{P}\p{S}]/gu, "").toLowerCase();
}

export function hasDistinctTopicAngles(angles: TopicAngle[]) {
  if (angles.length !== 5 || angles.some(a => !a.title.trim() || !a.approach.trim() || !a.reason.trim())) return false;
  return new Set(angles.map(a => comparisonKey(a.title))).size === 5
    && new Set(angles.map(a => comparisonKey(a.approach))).size === 5;
}

export function isCompleteHotTopicDraft(draft: string) {
  const blocks = [...draft.matchAll(/^([1-5])[.、]\s*(.+)\n怎么做[：:]\s*([^\n]+)\n说明[：:]\s*([^\n]+)/gm)];
  const numbers = draft.match(/^\d+[.、]/gm) ?? [];
  if (numbers.length !== 5 || blocks.some((b, i) => Number(b[1]) !== i + 1)) return false;
  return hasDistinctTopicAngles(blocks.map(b => ({ title: b[2], approach: b[3], reason: b[4] })));
}
